export function hashDeviceSecret(secret: string): string {
  const pepper =
    process.env.IOT_DEVICE_HMAC_PEPPER ||
    "healthos-dev-hmac-pepper-do-not-use-in-prod";
  return crypto
    .createHmac("sha256", pepper)
    .update(secret)
    .digest("hex");
}

